#!/usr/bin/env python3
"""Generate the LVGL 9 CJK font subsets used by the notification app.

Why this script exists instead of `lv_font_conv`: the pinned lv_font_conv (1.5.3,
2021) is reported to emit corrupt PLAIN bitmaps under current Node.js, and the
failure mode is a screen full of noise that looks like a font-selection bug. This
generator rasterises with Pillow/FreeType, writes LVGL's PLAIN 4bpp format
directly, and can re-parse its own C output and compare it pixel by pixel with the
rasterisation that produced it (`--verify`).

Layout choices (see docs/reference/shinku-chen/lvgl-cjk-font-subsets.md):
  * one dense `FORMAT0_TINY` cmap for ASCII (0x20-0x7E);
  * one `SPARSE_TINY` cmap for everything else - a dense table over the whole CJK
    block would waste flash and `FORMAT0_FULL` is not safe on this LVGL version.
  * PLAIN format (bitmap_format = 0), 4 bpp, high nibble first, every glyph starting
    on a byte boundary.

Usage:
    # needs Pillow (FreeType) available to this interpreter
    python tools/gen_cjk_font.py --font assets/fonts/NotoSansSC-Regular.otf --verify
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:  # pragma: no cover - environment check
    sys.exit("Pillow is required: pip install pillow")

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_FONT = ROOT / "assets" / "fonts" / "NotoSansSC-Regular.otf"
DEFAULT_INVENTORY = ROOT / "assets" / "fonts" / "app_font_inventory.txt"
DEFAULT_OUT_DIR = ROOT / "assets" / "fonts"

ASCII_FIRST = 0x20
ASCII_LAST = 0x7E

# Punctuation the UI and Chinese notification text actually contain. GB2312 level-1
# only covers ideographs, so full-width punctuation has to be listed explicitly.
PUNCTUATION = [
    0x00B7,                                  # ·
    0x2013, 0x2014,                          # – —
    0x2018, 0x2019, 0x201C, 0x201D,          # ‘ ’ “ ”
    0x2026,                                  # …
    0x3000, 0x3001, 0x3002,                  # 　 、 。
    0x3008, 0x3009, 0x300A, 0x300B,          # 《 》 〈 〉
    0x300C, 0x300D, 0x300E, 0x300F,          # 「 」 『 』
    0x3010, 0x3011, 0x3014, 0x3015,          # 【 】 〔 〕
    0xFF01, 0xFF08, 0xFF09, 0xFF0C,          # ！ （ ） ，
    0xFF1A, 0xFF1B, 0xFF1F, 0xFF5E, 0xFFE5,  # ： ； ？ ～ ￥
]


GENERAL_HANZI_PATH = ROOT / "assets" / "fonts" / "general_hanzi.txt"


def load_general_hanzi() -> list[int]:
    """《通用规范汉字表》(2013) 全部 8105 字中能进本字库的部分。

    工牌的公司名/姓名是运行时用户输入的，生僻字无法静态预检，所以直接放全量
    （一级 3500 + 二级 3000 + 三级 1605，喆/堃/燊/垚/淼/鑫/珲 等姓氏人名、地名、
    科技术语用字都在内），避免以后逐个追加。

    ⚠ 规范字表里有 196 个 CJK 扩展 B 区字（码点 > U+FFFF，如 𬉼/𠳐/𥻗）。这些是
    astral 平面字符，LVGL 的 fmt_txt cmap 用 UTF-16 单元索引（见 app_font_coverage.c
    顶部注释），根本无法渲染，故过滤掉——不是妥协，是这条渲染管线就不支持它们。
    """
    chars: list[int] = []
    skipped = 0
    for line in GENERAL_HANZI_PATH.read_text(encoding="utf-8").splitlines():
        ch = line.strip()
        if len(ch) != 1:
            continue
        cp = ord(ch)
        if cp > 0xFFFF:
            skipped += 1
            continue
        chars.append(cp)
    if skipped:
        print(f"  注意: 跳过 {skipped} 个扩展 B 区汉字(>U+FFFF, LVGL UTF-16 cmap 不支持)")
    if len(chars) < 7900:
        raise SystemExit(
            f"{GENERAL_HANZI_PATH.name}: expected ~7900 BMP chars, got {len(chars)}")
    return chars


# GB2312 level-1 is the supported CJK baseline: ~99.5% of real message text and
# every string this application displays. Add a code point here when a needed
# character sits outside it (tools/check_font_coverage.py reports those by name).
# Keep the list short: each size costs roughly 130-200 bytes per glyph.
EXTRA_HANZI = [
    0x549A,  # 咚 - 叮咚
    0x54D4,  # 哔 - 哔哩哔哩
]


def build_inventory() -> list[int]:
    cps = set(range(ASCII_FIRST, ASCII_LAST + 1))
    cps.update(PUNCTUATION)
    cps.update(load_general_hanzi())
    cps.update(EXTRA_HANZI)
    return sorted(cps)


def write_inventory(path: Path, cps: list[int]) -> None:
    lines = [
        "# app_font_inventory.txt - code points embedded in app_font_16 / app_font_20",
        "# Generated by tools/gen_cjk_font.py. Keep this file in version control:",
        "# tools/check_font_coverage.py fails the static gate when a UI string uses a",
        "# character that is not listed here, and assets/fonts/app_font_coverage.c",
        "# (the runtime table behind app_font_covers()) is built from this same list.",
    ]
    for cp in cps:
        lines.append(f"U+{cp:04X} {chr(cp)}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


COVERAGE_HEADER = """\
/*
 * app_font_coverage.h - which code points the embedded UI fonts can draw.
 *
 * Generated by tools/gen_cjk_font.py - do not edit by hand.
 * This file has no LVGL dependency so host tests and platform-independent
 * modules (main/app_notify.c) can ask the same question the renderer will ask.
 */
#ifndef APP_FONT_COVERAGE_H
#define APP_FONT_COVERAGE_H

#include <stdbool.h>
#include <stdint.h>

#ifdef __cplusplus
extern "C" {
#endif

/* True when every embedded size of the UI font contains this code point. */
bool app_font_covers(uint32_t codepoint);

/* Number of code points in the embedded coverage table. */
int app_font_coverage_count(void);

#ifdef __cplusplus
}
#endif

#endif /* APP_FONT_COVERAGE_H */
"""


def emit_coverage(out_dir: Path, cps: list[int]) -> Path:
    """Emit the LVGL-free coverage table used at runtime to drop unsupported text."""
    (out_dir / "app_font_coverage.h").write_text(COVERAGE_HEADER, encoding="utf-8")

    out: list[str] = []
    out.append("/*")
    out.append(" * app_font_coverage.c - generated by tools/gen_cjk_font.py, do not edit.")
    out.append(f" * Source: {len(cps)} code points (ASCII + CJK punctuation + GB2312 level-1/2).")
    out.append(" */")
    out.append("")
    out.append('#include "app_font_coverage.h"')
    out.append("")
    out.append("/* Sorted, BMP only: LVGL cmaps index UTF-16 units, so astral planes")
    out.append(" * are never covered by the embedded fonts. */")
    out.append("static const uint16_t s_cps[] = {")
    for offset in range(0, len(cps), 12):
        out.append("    " + ", ".join(f"0x{cp:04x}" for cp in cps[offset:offset + 12]) + ",")
    out.append("};")
    out.append("")
    out.append("#define APP_FONT_CPS_COUNT ((int)(sizeof(s_cps) / sizeof(s_cps[0])))")
    out.append("")
    out.append("bool app_font_covers(uint32_t codepoint)")
    out.append("{")
    out.append("    if (codepoint < 0x20u || codepoint > 0xFFFFu) {")
    out.append("        return false;")
    out.append("    }")
    out.append("")
    out.append("    int lo = 0;")
    out.append("    int hi = APP_FONT_CPS_COUNT - 1;")
    out.append("    while (lo <= hi) {")
    out.append("        int mid = lo + (hi - lo) / 2;")
    out.append("        uint16_t value = s_cps[mid];")
    out.append("        if (value == (uint16_t)codepoint) {")
    out.append("            return true;")
    out.append("        }")
    out.append("        if (value < (uint16_t)codepoint) {")
    out.append("            lo = mid + 1;")
    out.append("        } else {")
    out.append("            hi = mid - 1;")
    out.append("        }")
    out.append("    }")
    out.append("    return false;")
    out.append("}")
    out.append("")
    out.append("int app_font_coverage_count(void)")
    out.append("{")
    out.append("    return APP_FONT_CPS_COUNT;")
    out.append("}")
    out.append("")

    path = out_dir / "app_font_coverage.c"
    path.write_text("\n".join(out), encoding="utf-8")
    return path


class Glyph:
    __slots__ = ("cp", "adv_w", "box_w", "box_h", "ofs_x", "ofs_y", "bitmap", "pixels",
                 "bitmap_index")

    def __init__(self, cp: int, adv_w: int, box_w: int, box_h: int,
                 ofs_x: int, ofs_y: int, bitmap: bytes, pixels: bytes) -> None:
        self.cp = cp
        self.adv_w = adv_w
        self.box_w = box_w
        self.box_h = box_h
        self.ofs_x = ofs_x
        self.ofs_y = ofs_y
        self.bitmap = bitmap        # PLAIN 4bpp bytes exactly as LVGL expects
        self.pixels = pixels        # 4-bit values, one per pixel, for verification
        self.bitmap_index = 0


def rasterize(font: "ImageFont.FreeTypeFont", cp: int) -> Glyph:
    ch = chr(cp)
    # anchor="ls" == origin at left of the advance width, on the baseline.
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    box_w = max(0, x1 - x0)
    box_h = max(0, y1 - y0)
    adv_w = int(round(font.getlength(ch) * 16))

    if box_w == 0 or box_h == 0:
        return Glyph(cp, adv_w, 0, 0, 0, 0, b"", b"")

    image = Image.new("L", (box_w, box_h), 0)
    draw = ImageDraw.Draw(image)
    draw.text((-x0, -y0), ch, font=font, fill=255, anchor="ls")

    # LVGL 的 PLAIN 4bpp 位图**不按行对齐**：lv_font_fmt_txt.c 里 bpp==4 的分支
    # 只有在 g_dsc->stride != 0 时才会在换行处重置半字节计数，否则 i 一路累加，
    # 等于把整个 box_w*box_h 当成一条连续的半字节流（高半字节在前）。
    # 之前这里按 (box_w+1)//2 给每行补齐字节 —— box_w 为偶数时两者等价，看起来
    # 正常；一旦 box_w 是奇数，每往下一行就整体错位半个像素，字形呈现斜切扭曲。
    total = (box_w * box_h + 1) // 2
    data = bytearray(total)
    values = bytearray(box_w * box_h)
    raster = image.load()
    for y in range(box_h):
        for x in range(box_w):
            value = (raster[x, y] * 15 + 127) // 255
            k = y * box_w + x
            values[k] = value
            if k % 2 == 0:
                data[k // 2] |= (value & 0x0F) << 4
            else:
                data[k // 2] |= value & 0x0F

    # ofs_x = left bearing, ofs_y = glyph bottom measured up from the baseline.
    return Glyph(cp, adv_w, box_w, box_h, x0, -y1, bytes(data), bytes(values))


def check_limits(glyphs: list[Glyph]) -> int:
    total = 0
    for g in glyphs:
        if g.box_w > 255 or g.box_h > 255:
            raise SystemExit(f"U+{g.cp:04X}: glyph box {g.box_w}x{g.box_h} exceeds 8-bit fields")
        if not (-128 <= g.ofs_x <= 127 and -128 <= g.ofs_y <= 127):
            raise SystemExit(f"U+{g.cp:04X}: offset outside int8 range")
        if g.adv_w > 4095:
            raise SystemExit(f"U+{g.cp:04X}: advance {g.adv_w}/16 px exceeds 12-bit field")
        g.bitmap_index = total
        total += len(g.bitmap)
    # 1 MiB 上限(LVGL 的 bitmap_index 是 20 位)由调用方判断:超了就拆成
    # 多个字体并用 fallback 链串起来,而不是在这里直接失败。
    return total


def split_glyphs(glyphs: list[Glyph], limit: int) -> list[list[Glyph]]:
    """把字形按位图字节数均分成若干块，每块 < limit，且每块都带完整 ASCII。

    emit_c 要求 dense ASCII cmap 完整，所以每个拆分出的字体都必须包含全套
    ASCII（开销 ~10KB，可忽略），否则它无法独立回退。返回的每块已按码点排序。
    """
    ascii_glyphs = [g for g in glyphs if ASCII_FIRST <= g.cp <= ASCII_LAST]
    rest = [g for g in glyphs if not (ASCII_FIRST <= g.cp <= ASCII_LAST)]
    budget = limit - sum(len(g.bitmap) for g in ascii_glyphs)
    if budget <= 0:
        raise SystemExit("ASCII glyphs alone exceed the bitmap limit")

    chunks: list[list[Glyph]] = []
    cur: list[Glyph] = []
    cur_bytes = 0
    for g in rest:
        if cur and cur_bytes + len(g.bitmap) > budget:
            chunks.append(sorted(ascii_glyphs + cur, key=lambda x: x.cp))
            cur = []
            cur_bytes = 0
        cur.append(g)
        cur_bytes += len(g.bitmap)
    if cur:
        chunks.append(sorted(ascii_glyphs + cur, key=lambda x: x.cp))
    return chunks


def emit_c(path: Path, name: str, size: int, font_file: Path, glyphs: list[Glyph],
           line_height: int, base_line: int, fallback: str | None = None) -> None:
    ascii_glyphs = [g for g in glyphs if ASCII_FIRST <= g.cp <= ASCII_LAST]
    sparse_glyphs = [g for g in glyphs if not (ASCII_FIRST <= g.cp <= ASCII_LAST)]
    if [g.cp for g in ascii_glyphs] != list(range(ASCII_FIRST, ASCII_LAST + 1)):
        raise SystemExit("ASCII range must be complete for the dense cmap")

    if not sparse_glyphs:
        raise SystemExit("no sparse glyphs to emit")
    sparse_start = sparse_glyphs[0].cp
    sparse_end = sparse_glyphs[-1].cp
    sparse_len = sparse_end - sparse_start + 1
    if sparse_len > 0xFFFF:
        raise SystemExit("sparse cmap range does not fit in uint16")

    out: list[str] = []
    out.append("/*******************************************************************************")
    out.append(f" * Size: {size} px")
    out.append(" * Bpp: 4")
    out.append(" * Generated by tools/gen_cjk_font.py - do not edit by hand.")
    out.append(f" * Source font: {font_file.name} (Noto Sans SC, SIL Open Font License 1.1)")
    out.append(f" * Glyphs: {len(glyphs)} code points, PLAIN 4bpp, FORMAT0_TINY + SPARSE_TINY")
    out.append(" ******************************************************************************/")
    out.append("")
    out.append('#include "lvgl.h"')
    out.append("")
    out.append(f"#ifndef LV_FONT_{name.upper()}")
    out.append(f"    #define LV_FONT_{name.upper()} 1")
    out.append("#endif")
    out.append("")
    out.append(f"#if LV_FONT_{name.upper()}")
    out.append("")
    out.append("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {")

    for g in glyphs:
        if not g.bitmap:
            continue
        label = chr(g.cp) if g.cp >= 0x20 and g.cp != 0x7F else f"U+{g.cp:04X}"
        out.append(f"    /* U+{g.cp:04X} \"{label}\" */")
        for offset in range(0, len(g.bitmap), 16):
            chunk = g.bitmap[offset:offset + 16]
            out.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    out.append("};")
    out.append("")

    out.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    out.append("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},"
               " /* id = 0 reserved */")
    for g in glyphs:
        out.append(f"    {{.bitmap_index = {g.bitmap_index}, .adv_w = {g.adv_w}, "
                   f".box_w = {g.box_w}, .box_h = {g.box_h}, "
                   f".ofs_x = {g.ofs_x}, .ofs_y = {g.ofs_y}}},")
    out.append("};")
    out.append("")

    out.append("static const uint16_t unicode_list_1[] = {")
    items = [g.cp - sparse_start for g in sparse_glyphs]
    for offset in range(0, len(items), 12):
        out.append("    " + ", ".join(f"0x{v:04x}" for v in items[offset:offset + 12]) + ",")
    out.append("};")
    out.append("")

    ascii_glyph_id_start = 1
    sparse_glyph_id_start = ascii_glyph_id_start + len(ascii_glyphs)
    out.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    out.append("    {")
    out.append(f"        .range_start = {ASCII_FIRST}, .range_length = {ASCII_LAST - ASCII_FIRST + 1}, "
               f".glyph_id_start = {ascii_glyph_id_start},")
    out.append("        .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, "
               ".type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY")
    out.append("    },")
    out.append("    {")
    out.append(f"        .range_start = {sparse_start}, .range_length = {sparse_len}, "
               f".glyph_id_start = {sparse_glyph_id_start},")
    out.append(f"        .unicode_list = unicode_list_1, .glyph_id_ofs_list = NULL, "
               f".list_length = {len(sparse_glyphs)}, "
               f".type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY")
    out.append("    }")
    out.append("};")
    out.append("")

    out.append("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    out.append("    .glyph_bitmap = glyph_bitmap,")
    out.append("    .glyph_dsc = glyph_dsc,")
    out.append("    .cmaps = cmaps,")
    out.append("    .kern_dsc = NULL,")
    out.append("    .kern_scale = 0,")
    out.append("    .cmap_num = 2,")
    out.append("    .bpp = 4,")
    out.append("    .kern_classes = 0,")
    out.append("    .bitmap_format = 0,")
    out.append("};")
    out.append("")
    if fallback:
        out.append(f"extern const lv_font_t {fallback};")
        out.append("")
    out.append(f"const lv_font_t {name} = {{")
    out.append("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    out.append("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    out.append(f"    .line_height = {line_height},")
    out.append(f"    .base_line = {base_line},")
    out.append("    .subpx = LV_FONT_SUBPX_NONE,")
    out.append("    .underline_position = -2,")
    out.append("    .underline_thickness = 1,")
    out.append("    .dsc = &font_dsc,")
    if fallback:
        out.append(f"    .fallback = &{fallback},")
    else:
        out.append("    .fallback = NULL,")
    out.append("};")
    out.append("")
    out.append(f"#endif /* LV_FONT_{name.upper()} */")
    out.append("")

    path.write_text("\n".join(out), encoding="utf-8")


def verify_c(path: Path, name: str, glyphs: list[Glyph]) -> None:
    """Re-read the emitted C file, decode it the way LVGL will, compare pixels."""
    import re

    text = path.read_text(encoding="utf-8")

    bitmap_text = re.search(r"glyph_bitmap\[\] = \{(.*?)\n\};", text, re.S)
    if not bitmap_text:
        raise SystemExit(f"{path.name}: glyph_bitmap array not found")
    bitmap = bytes(int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]{2})", bitmap_text.group(1)))

    dsc = [(int(a), int(b), int(c), int(d), int(e), int(f)) for a, b, c, d, e, f in re.findall(
        r"\{\.bitmap_index = (\d+), \.adv_w = (\d+), \.box_w = (\d+), \.box_h = (\d+), "
        r"\.ofs_x = (-?\d+), \.ofs_y = (-?\d+)\}", text)]
    if len(dsc) != len(glyphs) + 1:
        raise SystemExit(f"{path.name}: expected {len(glyphs) + 1} glyph descriptors, "
                         f"found {len(dsc)}")

    ascii_list = re.search(r"range_start = (\d+), \.range_length = (\d+), "
                           r"\.glyph_id_start = (\d+),\s*\.unicode_list = NULL", text)
    sparse_list = re.search(r"unicode_list_1\[\] = \{(.*?)\n\};", text, re.S)
    sparse_cmap = re.search(r"range_start = (\d+), \.range_length = (\d+), "
                            r"\.glyph_id_start = (\d+),\s*\.unicode_list = unicode_list_1", text)
    if not (ascii_list and sparse_list and sparse_cmap):
        raise SystemExit(f"{path.name}: cmap tables not found")
    unicode_list = [int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]{4})", sparse_list.group(1))]

    ascii_start, ascii_len, ascii_gid = (int(g) for g in ascii_list.groups())
    sparse_start, sparse_len, sparse_gid = (int(g) for g in sparse_cmap.groups())
    expected = {g.cp: g for g in glyphs}

    checked = 0
    for cp, glyph in expected.items():
        # Cmap lookup, mirroring lv_font_fmt_txt.c
        if ascii_start <= cp < ascii_start + ascii_len:
            gid = ascii_gid + (cp - ascii_start)
        elif sparse_start <= cp < sparse_start + sparse_len:
            rcp = cp - sparse_start
            try:
                index = unicode_list.index(rcp)
            except ValueError:
                raise SystemExit(f"{path.name}: U+{cp:04X} missing from unicode_list")
            gid = sparse_gid + index
        else:
            raise SystemExit(f"{path.name}: U+{cp:04X} outside both cmaps")

        if gid >= len(dsc):
            raise SystemExit(f"{path.name}: U+{cp:04X} maps to glyph id {gid} out of range")
        bitmap_index, adv_w, box_w, box_h, ofs_x, ofs_y = dsc[gid]
        got = (adv_w, box_w, box_h, ofs_x, ofs_y)
        want = (glyph.adv_w, glyph.box_w, glyph.box_h, glyph.ofs_x, glyph.ofs_y)
        if got != want:
            raise SystemExit(f"{path.name}: U+{cp:04X} descriptor {got} != {want}")

        size = (box_w * box_h + 1) // 2
        chunk = bitmap[bitmap_index:bitmap_index + size]
        if chunk != glyph.bitmap:
            raise SystemExit(f"{path.name}: U+{cp:04X} bitmap mismatch")

        # 按 LVGL 的 PLAIN 读取方式来解：**整块连续半字节流，不按行对齐**
        # （lv_font_fmt_txt.c 的 bpp==4 分支，stride==0 时半字节计数不换行重置）。
        # 早先这里是按 (box_w+1)//2 逐行解码，和错误的打包方式互相印证，
        # 所以测试全绿但真机字形斜切。
        if box_w and box_h:
            for y in range(box_h):
                for x in range(box_w):
                    k = y * box_w + x
                    byte = chunk[k // 2]
                    value = (byte >> 4) if k % 2 == 0 else (byte & 0x0F)
                    if value != glyph.pixels[k]:
                        raise SystemExit(
                            f"{path.name}: U+{cp:04X} pixel ({x},{y}) mismatch")
            checked += 1

    print(f"  verify {path.name}: {len(glyphs)} glyphs, {len(bitmap)} bitmap bytes OK")


def cmap_code_points(path: Path) -> set[int]:
    """Code points reachable through the cmaps of an emitted LVGL font file."""
    import re

    text = path.read_text(encoding="utf-8")
    cps: set[int] = set()

    dense = re.search(r"range_start = (\d+), \.range_length = (\d+), "
                      r"\.glyph_id_start = \d+,\s*\.unicode_list = NULL", text)
    if dense:
        start, length = int(dense.group(1)), int(dense.group(2))
        cps.update(range(start, start + length))

    sparse = re.search(r"unicode_list_1\[\] = \{(.*?)\n\};", text, re.S)
    sparse_cmap = re.search(r"range_start = (\d+), \.range_length = (\d+), "
                            r"\.glyph_id_start = \d+,\s*\.unicode_list = unicode_list_1", text)
    if sparse and sparse_cmap:
        base = int(sparse_cmap.group(1))
        cps.update(base + int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]{4})", sparse.group(1)))

    if not cps:
        raise SystemExit(f"{path.name}: no cmap code points found")
    return cps


def verify_coverage(path: Path, font_paths: list[Path]) -> None:
    """The runtime coverage table must match every embedded font size exactly."""
    import re

    table = re.search(r"s_cps\[\] = \{(.*?)\n\};", path.read_text(encoding="utf-8"), re.S)
    if not table:
        raise SystemExit(f"{path.name}: s_cps table not found")
    values = [int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]{4})", table.group(1))]
    if values != sorted(set(values)):
        raise SystemExit(f"{path.name}: coverage table is not sorted and unique")
    covered = set(values)

    # 拆分后的字体(主 + 副)一起才算完整覆盖:比较【所有字体的并集】与覆盖率表。
    font_cps: set[int] = set()
    for font_path in font_paths:
        font_cps |= cmap_code_points(font_path)
    missing = font_cps - covered
    extra = covered - font_cps
    if missing or extra:
        raise SystemExit(
            f"{path.name} disagrees with embedded fonts: "
            f"missing {sorted(missing)[:8]}, extra {sorted(extra)[:8]}")

    print(f"  verify {path.name}: {len(covered)} code points match "
          f"{', '.join(p.name for p in font_paths)}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, default=DEFAULT_FONT)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    parser.add_argument("--inventory", type=Path, default=DEFAULT_INVENTORY)
    parser.add_argument("--sizes", default="16,20")
    parser.add_argument("--metrics", choices=("tight", "font"), default="tight",
                        help="tight: derive line_height/base_line from real glyph "
                             "extents (compact, never clips); font: use the OTF "
                             "ascent/descent (loose, ~1.5x line spacing)")
    parser.add_argument("--verify", action="store_true",
                        help="re-parse the generated C files and compare bitmaps")
    args = parser.parse_args()

    if not args.font.exists():
        print(f"font not found: {args.font}", file=sys.stderr)
        return 1
    args.out_dir.mkdir(parents=True, exist_ok=True)

    cps = build_inventory()
    write_inventory(args.inventory, cps)
    coverage_path = emit_coverage(args.out_dir, cps)
    print(f"inventory: {len(cps)} code points -> {args.inventory.relative_to(ROOT)}")
    print(f"coverage:  {len(cps)} code points -> {coverage_path.relative_to(ROOT)}")

    sizes = [int(s) for s in args.sizes.split(",") if s.strip()]
    font_paths: list[Path] = []
    for size in sizes:
        name = f"app_font_{size}"
        font = ImageFont.truetype(str(args.font), size)
        font_ascent, font_descent = font.getmetrics()

        glyphs = sorted((rasterize(font, cp) for cp in cps), key=lambda g: g.cp)
        total = check_limits(glyphs)

        if args.metrics == "tight":
            # LVGL 的语义(见 lv_draw_label.c):
            #   glyph 底边 = baseline - ofs_y, 顶边 = 底边 - box_h
            # 生成时 ofs_y = -y1, 因此 ofs_y 为负表示字形伸到基线之下。
            #   base_line 必须 >= 向下的最大伸出量, 否则下缘与下一行重叠;
            #   line_height - base_line 必须 >= 向上的最大伸出量。
            descent = max(0, max(-g.ofs_y for g in glyphs))
            ascent = max(0, max(g.ofs_y + g.box_h for g in glyphs))
            line_height = ascent + descent
            # 自检: 每个字形必须完整落在 [0, line_height) 行盒内。
            for g in glyphs:
                top = ascent - (g.ofs_y + g.box_h)
                bottom = top + g.box_h
                if top < 0 or bottom > line_height:
                    raise SystemExit(
                        f"{name}: U+{g.cp:04X} out of line box "
                        f"(top {top}, bottom {bottom}, line_height {line_height})")
        else:
            ascent, descent = font_ascent, font_descent
            line_height = ascent + descent

        # bitmap_index 是 20 位，单字体位图必须 < 1 MiB。超了就按字节数均分，
        # 用 fallback 链串成多个字体。
        limit = (1 << 20) - 1
        chunks = [glyphs] if total < limit else split_glyphs(glyphs, limit)
        chunk_names = [name] + [
            f"{name}_ext" + (str(i) if i > 1 else "") for i in range(1, len(chunks))
        ]

        for i, chunk in enumerate(chunks):
            check_limits(chunk)   # 重算 bitmap_index（块内顺序已变）
            nm = chunk_names[i]
            fallback = chunk_names[i + 1] if i + 1 < len(chunks) else None
            path = args.out_dir / f"{nm}.c"
            font_paths.append(path)
            emit_c(path, nm, size, args.font, chunk, line_height, descent,
                   fallback=fallback)
            if args.verify:
                verify_c(path, nm, chunk)

        if len(chunks) == 1:
            print(f"{name}: {len(glyphs)} glyphs, bitmap {total / 1024:.1f} KiB, "
                  f"line_height {line_height} (ascent {ascent}, base_line {descent}), "
                  f"font metrics {font_ascent}+{font_descent} -> "
                  f"{font_paths[-1].relative_to(ROOT)}")
        else:
            parts = " + ".join(
                f"{sum(len(g.bitmap) for g in c) / 1024:.1f}" for c in chunks)
            print(f"{name}: 拆分 {parts} KiB（{len(chunks)} 块，"
                  f"{', '.join(str(len(c)) for c in chunks)} 字形）, line_height {line_height}")

    if args.verify:
        verify_coverage(coverage_path, font_paths)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
